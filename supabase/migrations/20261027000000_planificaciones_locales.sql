-- Respaldo idempotente por elemento de las colecciones locales de la app.
create table if not exists public.planificaciones_locales (
  id integer generated by default as identity primary key,
  session_id varchar(320) not null,
  tipo varchar(16) not null,
  item_id varchar(128) not null,
  form text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ck_planificaciones_locales_tipo
    check (tipo in ('diario', 'semanal', 'bt', 'cnc', 'evaluacion')),
  constraint uq_planificaciones_locales_owner_item
    unique (session_id, tipo, item_id)
);

create index if not exists idx_planificaciones_locales_owner
  on public.planificaciones_locales (session_id, tipo);

alter table public.planificaciones_locales enable row level security;
revoke all on public.planificaciones_locales from anon, authenticated;
